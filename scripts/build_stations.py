#!/usr/bin/env python3
"""Turn data/stations.txt into src/stations.js.

The page loads src/stations.js with a plain <script> tag so index.html opens
straight from the filesystem — no dev server, no fetch(), no CORS.

    python3 scripts/build_stations.py
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "data" / "stations.txt"
OUT = ROOT / "src" / "stations.js"

ROW = re.compile(r"^\d+\|")


def parse(text):
    stations = []
    for lineno, raw in enumerate(text.splitlines(), 1):
        line = raw.strip()
        if not ROW.match(line):
            continue
        parts = line.split("|")
        if len(parts) != 7:
            sys.exit(f"{SRC}:{lineno}: expected 7 fields, got {len(parts)}")
        sid, name, borough, routes, lat, lon, ada = parts
        stations.append(
            {
                "id": int(sid),
                "name": name,
                "borough": borough,
                "routes": [r for r in routes.split(",") if r],
                "lat": float(lat),
                "lon": float(lon),
                "ada": ada == "1",
            }
        )
    return stations


def main():
    stations = parse(SRC.read_text(encoding="utf-8"))
    if not stations:
        sys.exit(f"no station rows parsed from {SRC}")

    ids = [s["id"] for s in stations]
    if len(set(ids)) != len(ids):
        dupes = sorted({i for i in ids if ids.count(i) > 1})
        sys.exit(f"duplicate station ids in {SRC}: {dupes}")

    body = "\n".join(
        "  " + json.dumps(s, separators=(",", ":"), ensure_ascii=False) + ","
        for s in stations
    )
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "// GENERATED by scripts/build_stations.py — edit data/stations.txt instead.\n"
        f"window.STATIONS = [\n{body}\n];\n",
        encoding="utf-8",
    )
    print(f"wrote {len(stations)} stations to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
